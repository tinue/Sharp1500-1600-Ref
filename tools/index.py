#!/usr/bin/env python3
"""Regenerate INDEX.md and the file tables in every topic README.md.

    python3 tools/index.py          write the files
    python3 tools/index.py --check  exit 1 if they are stale

A topic README keeps its hand-written text; only the block between
<!-- files:begin --> and <!-- files:end --> is generated from the document headers.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from refdocs import *

BEGIN, END = "<!-- files:begin -->", "<!-- files:end -->"

def table(files, relto):
    rows = ["| File | Model | Status | KB | What it answers |", "|---|---|---|---|---|"]
    for f in files:
        if f == "Programming/prompts/LH5801-Assembly-Prompt.md":
            link = os.path.relpath(f, relto).replace(os.sep, "/")
            rows.append(f"| [{os.path.basename(f)}]({link}) | 1500+1600 | generated | {kb(f)} | Paste-ready LH5801 assembly prompt, built from the parts by `tools/build-prompts.py`. |")
            continue
        t, h = header(read(f))
        link = os.path.relpath(f, relto).replace(os.sep, "/")
        rows.append(f"| [{os.path.basename(f)}]({link}) | {machines(h.get('Scope', ''))} | {h.get('Status', '?')} | {kb(f)} | {h.get('Summary', '')} |")
    return "\n".join(rows)

def render():
    out = {}
    idx = ["# Index", "",
           "Generated by `tools/index.py`. Do not edit. One row per reference document; the topic `README.md` files say more.", "",
           "**Rules for agents.** Pick the topic, read its `README.md`, then the one document you need. "
           "Files over 25 KB: run `grep -n '^## ' <file>` first and read only the section you need. "
           "Model: `1500` = PC-1500 and PC-1500A, `1600` = PC-1600, `1500+1600` = both. "
           "Status: `draft` < `cited` < `ROM-verified` < `emulator-verified` (see CONVENTIONS.md).", ""]
    total = 0
    for t in topics():
        files = docs(t)
        if not files: continue
        total += len(files)
        idx += [f"## {t}", "", table(files, "."), ""]
        rp = f"{t}/README.md"
        cur = read(rp) if os.path.exists(os.path.join(ROOT, rp)) else f"# {t}\n\n{BEGIN}\n{END}\n"
        if BEGIN not in cur:
            cur = cur.rstrip("\n") + f"\n\n## Documents\n\n{BEGIN}\n{END}\n"
        a, rest = cur.split(BEGIN, 1)
        _, z = rest.split(END, 1)
        out[rp] = a + BEGIN + "\n" + table(files, t) + "\n" + END + z
    idx.insert(2, f"{total} documents.")
    out["INDEX.md"] = "\n".join(idx).rstrip("\n") + "\n"
    return out

if __name__ == "__main__":
    stale = []
    for rel, text in render().items():
        p = os.path.join(ROOT, rel)
        cur = open(p, encoding="utf8").read() if os.path.exists(p) else None
        if cur != text:
            stale.append(rel)
            if "--check" not in sys.argv:
                open(p, "w", encoding="utf8").write(text)
    if "--check" in sys.argv:
        for s in stale: print("stale:", s)
        sys.exit(1 if stale else 0)
    print("updated:", ", ".join(stale) if stale else "nothing")
