#!/usr/bin/env python3
"""Generate the paste-ready LH5801 prompt from its parts.

    python3 tools/build-prompts.py          write Programming/prompts/LH5801-Assembly-Prompt.md
    python3 tools/build-prompts.py --check  exit 1 if it is stale

The parts are the source; edit them, never the generated file.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from refdocs import ROOT, read

OUT = "Programming/prompts/LH5801-Assembly-Prompt.md"
G = "Programming/LH5801-Assembly-Guide.md"
AR = "CPU/LH5801-Architecture.md"
IS = "CPU/LH5801-Instruction-Set.md"
SV = "Firmware/PC-1500-System-Variables.md"
RR = "Firmware/PC-1500-ROM-Routines.md"
# (file, heading prefix) in the order of the finished prompt; None = the text before the first ## of the guide
ORDER = [(G, None), (G, "Quick Reference Card"), (AR, "Architecture Overview"), (AR, "Registers and Flags"),
         (AR, "Addressing Mode Reference"), (AR, "Memory Access and Bank Switching"), (G, "sdas Assembler Syntax"),
         (AR, "What Doesn"), (G, "Common Patterns and Idioms"), (IS, "Instruction Set Reference"),
         (SV, "PC-1500 System Reference"), (RR, "ROM Subroutine Reference"), (G, "Common Assembler Macros"),
         (G, "Appendix: Converting"), (G, "Writing a User Guide")]

def body(rel):
    """Document without its title, header block and split note; as (pre, [(heading, text)])."""
    lines = read(rel).split("\n")[1:]
    out, fence, i = [], False, 0
    while i < len(lines) and (not lines[i].strip() or re.match(r"^(Summary|Scope|Sources|Status):", lines[i]) or lines[i].startswith(">")):
        i += 1
    pre, chunks, cur = [], [], None
    for ln in lines[i:]:
        if ln.lstrip().startswith(("```", "~~~")): fence = not fence
        if not fence and ln.startswith("## "):
            cur = [ln, []]; chunks.append(cur); continue
        (cur[1] if cur else pre).append(ln)
    return "\n".join(pre).strip("\n"), [(h, "\n".join(b).strip("\n")) for h, b in chunks]

def build():
    cache = {}
    parts = ["# Sharp LH5801 Assembly Language Guide",
             "<!-- GENERATED by tools/build-prompts.py from Programming/LH5801-Assembly-Guide.md, CPU/LH5801-Architecture.md, "
             "CPU/LH5801-Instruction-Set.md, Firmware/PC-1500-System-Variables.md and Firmware/PC-1500-ROM-Routines.md. Do not edit. -->"]
    for f, pfx in ORDER:
        if f not in cache: cache[f] = body(f)
        pre, chunks = cache[f]
        if pfx is None:
            if pre: parts.append(pre)
            continue
        hit = [(h, t) for h, t in chunks if h[3:].startswith(pfx)]
        if len(hit) != 1: raise SystemExit(f"{f}: expected one section {pfx!r}, found {len(hit)}")
        parts.append(hit[0][0] + ("\n\n" + hit[0][1] if hit[0][1] else ""))
    return "\n\n".join(parts) + "\n"

if __name__ == "__main__":
    text = build()
    p = os.path.join(ROOT, OUT)
    cur = open(p, encoding="utf8").read() if os.path.exists(p) else None
    if "--check" in sys.argv:
        if cur != text: print("stale:", OUT); sys.exit(1)
        sys.exit(0)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf8").write(text)
    print("wrote", OUT, len(text) // 1024, "KB")
